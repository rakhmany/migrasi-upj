                        <h4 style="text-align: center;">Informasi Umum</h4>
                        <p align="justify">Berdasarkan Permendikbudristek Nomor 41 Tahun 2021 tentang RPL (Rekognisi Pembelajaran Lampau), yaitu untuk memberikan kesempatan seluas-luasnya bagi setiap individu untuk menempuh pendidikan formal, nonformal dan informal melalui fasilitas pembelajaran sepanjang hayat serta memberikan kesempatan penyetaraan terhadap kualifikasi tertentu. Untuk itu UPJ membuka jalur RPL untuk memberikan kesempatan kepada masyarakat untuk dapat melanjutkan pendidikan formal ke jenjang yang lebih tinggi yang pada akhirnya adalah pemberian bukti hasil belajar berupa Ijazah, transkrip nilai dan SKPI.</p>
