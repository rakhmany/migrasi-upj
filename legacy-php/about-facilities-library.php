                        <h2>Library</h2>
                        <p align="justify">Perpustakaan UPJ dibentuk seiring dengan berdirinya UPJ dengan Surat Keputusan Menteri Pendidikan Nasional Nomor 38/D/O/2011 tanggal 25 Februari 2011 tentang Izin Pendirian UPJ. Perpustakaan UPJ sendiri berada di lingkungan perguruan tinggi memiliki peran yang strategis untuk melaksanakan Tri Dharma Perguruan Tinggi, yakni pendidikan-pengajaran, penelitian dan pengabdian terhadap masyarakat. Bentuk nyata peran strategis Perpustakaan UPJ dalam melaksanakan Tri Dharma Perguruan Tinggi, yakni menyediakan koleksi bahan pustaka cetak dan elektronik sebagai referensi untuk mendukung pelaksanaan pendidikan-pengajaran, penelitian dan pengabdian terhadap masyarakat. UPJ sendiri memiliki misi sebagai Pusat Unggulan Universitas di bidang Urban Lifestyle dan Urban Development. Maka, Perpustakaan UPJ menerjemahkan misi tersebut ke dalam penyediaan koleksi bahan pustaka yang bertema Urban. </p>
                        <p align="justify">Sebagai public service area, dimana sivitas akademika UPJ dan masyarakat  umum dapat berkumpul, Perpustakaan UPJ membuka diri untuk memfasilitasi tersedianya berbagai sumber informasi yang relevan bagi semua stakeholders. Perpustakaan UPJ memiliki tujuan untuk mengurangi kemiskinan informasi dan meningkatkan potensi, kreativitas, dan kualitas pendidikan sivitas akademika UPJ dan masyarakat umum melalui program dan layanan sebagai berikut: pengembangan soft skill, peningkatan akses layanan baca, internet, E-Resources, penelusuran sumber penelitian, tugas, bisnis, informasi dan teknologi, layanan konsultasi bagi pengelola perpustakaan, pendidikan pemakai - literasi informasi dan layanan sirkulasi (peminjaman-pengembalian bahan pustaka) yang diperuntungkan bagi sivitas akademika UPJ yang sudah terdaftar sebagai anggota Perpustakaan UPJ aktif.</p>
                        <p align="justify">Perpustakaan UPJ terus menerus mengupdate sistem automasi sesuai perkembangan teknologi informasi di dunia perpustakaan. Software yang digunakan untuk mengelola koleksi bahan pustaka dan pelayanan saat ini adalah SLiMS versi Akasia sedangkan software pengelolaan repository karya tulis ilmiah internal dalam proses pengembangan. Alat penelusuran koleksi bahan pustaka Perpustakaan UPJ pun sudah  berbasis online, yakni Online Public Access Catalog (OPAC).</p>
