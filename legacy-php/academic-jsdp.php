                        <h4 style="text-align: center;">Informasi Umum</h4>
                        <p align="justify">Jaya Softskills Development Program  (JSDP) adalah program pemberian keterampilan (softskills) dan pengetahuan yang dilakukan oleh Universitas Pembangunan Jaya (UPJ). Program ini wajib diikuti oleh seluruh mahasiswa dan mencakup kegiatan dalam lingkup akademik maupun nonakademik. JSDP mulai diberlakukan sejak tahun ajaran 2015/2016 dan merupakan salah satu syarat kelulusan dari UPJ.</p>
                        <p align="justify">Sasaran JSDP adalah penanaman nilai-nilai Jaya dan perolehan softskills yang dianggap perlu dimiliki oleh seorang lulusan UPJ. Nilai-nilai Jaya yang dimaksudkan adalah:</p>
                        <ol>
                            <li>Integritas</li>
                            <li>Keadilan</li>
                            <li>Komitmen</li>
                            <li>Disiplin</li>
                            <li>Motivasi</li>
                        </ol>
                        <p align="justify">Sementara softskills yang ditanamkan adalah:</p>
                        <ol>
                            <li>Keterampilan Penalaran dan Keilmuan</li>
                            <li>Kepemimpinan dalam berorganisasi</li>
                            <li>Kewirausahaan</li>
                            <li>Keterampilan sesuai Profesi Akademik</li>
                            <li>Kepekaan terhadap lingkungan</li>
                            <li>Tanggung jawab sosial terhadap masyarakat</li>
                        </ol>
                        <p align="justify">Setiap kegiatan dalam JSDP akan mendapatkan poin sesuai ketentuan yang berlaku. Setiap mahasiswa harus mengumpulkan poin dalam jumlah minimal tertentu sebagai salah satu syarat kelulusan. Jumlah poin minimal untuk mahasiswa reguler tahun akademik 2015/2016 dan seterusnya adalah seribu (1000). Sementara untuk mahasiswa tahun akademik 2014/2015 adalah lima ratus (500) dan tahun akademik 2013/2014 adalah tiga ratus (300). Poin ini kemudian dicatat dalam Transkrip JSDP. Transkrip JSDP akan menjadi dokumentasi resmi universitas yang memberikan pengakuan serta penghargaan terhadap pembelajaran maupun prestasi mahasiswa UPJ di luar kegiatan kurikuler dan pada akhirnya meningkatan daya saing lulusan UPJ di pasar kerja.</p>
                        <p align="justify">Kegiatan JSDP terdiri dari 2 bagian besar, yaitu kegiatan wajib dan kegiatan pilihan. Kegiatan wajib yang harus diikuti adalah:</p>
                        <p align="justify">Program Orientasi Mahasiswa (PRIMA)<br>
                            Sejumlah pelatihan wajib yang diselenggarakan oleh Unit JSDP UPJ
                            Di luar kegiatan wajib di atas, mahasiswa dapat mengikuti kegiatan-kegiatan lain yang relvan dengan tujuan JSDP, baik di dalam lingkungan UPJ maupun di luar UPJ, baik di tingkat lokal, nasional sampai dengan internasional. Kegiatan-kegiatan tersebut antara lain adalah:</p>
                            <ol>
                                <li>Kegiatan berorganisasi</li>
                                <li>Seminar, lokakarya, pelatihan atau kuliah umum</li>
                                <li>Kerja sambilan atau magang</li>
                                <li>Lomba, kompetisi atau publikasi</li>
                            </ol>
                        <p align="justify">Poin JSDP yang sudah diperoleh mahasiswa yang bersangkutan harus divalidasi dengan melaporkan secara mandiri bukti-bukti kegiatan kepada Unit JSDP UPJ. Bukti-bukti tersebut dapat berupa sertifikat, piagam, piala, medali atau bentuk penghargaan lainnya, surat tugas, surat izin atu surat referensi, dokumentasi hasil karya atau bentuk-bentuk lainnya sesuai dengan ketentuan yang berlaku. Untuk kegiatan-kegiatan yang tidak dapat menyediakan surat atau dokumentasi formal, maka mahasiswa dapat menggunakan Formulir <a href="pdf/draft%20JSDP%20-%20Lembar%20Berita%20Acara%20Kegiatan.doc" target="_blank">JSDP F</a> – 003 (tautan ke Lembar Berita Acara Kegiatan) dan <a href="pdf/draft%20JSDP%20-%20Lembar%20Berita%20Acara%20Kegiatan.doc" target="_blank">F – 002</a> (tautan ke Lembar Kerja Kegiatan Eksternal). Selain itu, panduan poin JSDP dapat dilihat pada <a href="pdf/Poin JSDP.pdf" target="_blank">panduan poin JSDP</a>. </p>
