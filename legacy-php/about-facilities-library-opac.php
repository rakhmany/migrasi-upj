                        <h2>OPAC</h2>
                        <p align="justify">Online Public Access Catalog (OPAC) of UPJ Library is a search tool/enghine used to seek for internal literature resources owned by the UPJ Library. OPAC itself is a part of SLiMS feature with several facilities. The first facility is Simple search which allows the library user to easily and randomly search resources using several access points such authors, titles, subjects, location, and status. The second feature facility is Specific Search which expects user to be more specific in seeking library resources using more than one access points such as authors, titles, subjects ISBN, etc. The next facility is the user information which allows user to find out which resources are out being borrowed as it connects with the sirculation module. It also allows users to check how much longer they can borrow a certain resources as it connects with the users’ modules. The next facility is  the library administration. This facility is an advertisement tool to promote the library and to give complete information related to the use of OPAC. The last facility is Links to other libraries that aims to enable users to connect to other libraries and information center in order to search a specific resource needed which cannot be found at the university library. The OPAC of UPJ library can be accessed through <a href="http://opac.upj.ac.id/" target="_blank">//opac.upj.ac.id.</a></p>
